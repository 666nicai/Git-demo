/*# B 小明走格子

## 题目描述

从 A 点到 B 点有 n 个格子，小明现在要从 A 点到 B 点，小明吃了一些东西，补充了一下体力，他可以一步迈一个格子，也可以一步迈两个格子，也可以一步迈 3 个格子，也可以一步迈 4 个格子。请编写程序计算小明从 A 点到 B 点一共有多少种走法。

## 输入格式

输入包含多组数据，第一行为一个整数 m，m 不超过 10000，表示输入数据组数。接下来 m 行，每行为一个整数 n（n 不超过 100，且保证对应的结果小于 2^31），表示从 A 点到 B 点的格子数。

## 输出格式

输出为 m 个整数，表示对于每组数据小明从 A 点到 B 点的走法数。

## 输入样例

```
2
5
3
```

## 输出样例

```
15
4
```*/
// B 小明走格子
#include<bits/stdc++.h>
using namespace std;

int main(){
    int m;
    cin>>m;                     // 第一行是组数 m
    int q[10005],mx=0;          // q:每组询问的格子数,mx:其中最大值
    for(int i=0;i<m;i++){
        cin>>q[i];
        mx=max(mx,q[i]);
    }
    long long f[105]={1};       // f[i]:走到第 i 格的走法数,f[0]=1 是递推边界
    for(int i=1;i<=mx;i++)
        for(int k=1;k<=4;k++)   // 最后一步迈了 k 格
            if(i>=k) f[i]+=f[i-k];
    for(int i=0;i<m;i++){
        if(i) cout<<"\n";       // 换行放在每个答案前面,最后一行不再多一个换行
        cout<<f[q[i]];
    }
    return 0;
}
