/*# A 进制转换

## 题目描述

给定一个十进制正整数 $n$，请编写程序将其转换为 $K$ 进制（$1 < K < 10$）。

## 输入格式

输入为两个正整数 $n$ 和 $K$，含义如题目所述。$0 < n < 2^{31}, 1 < K < 10$。

## 输出格式

输出一行，为 $n$ 对应的 $K$ 进制数。

## 输入输出样例 #1

### 输入 #1

```
66 7
```

### 输出 #1

```
123
```

## 输入输出样例 #2

### 输入 #2

```
100 7
```

### 输出 #2

```
202
```*/
// A 进制转换
#include<bits/stdc++.h>        // 万能头文件
using namespace std;

int main(){
    long long n;                // n:要转换的十进制正整数,long long 保证边界安全
    int k;                      // k:目标进制,题目保证 1<k<10,所以每一位一定是 0~9
    cin>>n>>k;                  // 读入 n 和 k
    string s;                   // s:存放转换结果,低位先进,顺序是反的
    while(n>0){                 // 短除法:商除到 0 为止
        s+=(char)('0'+n%k);     // 取余数当最低位,加 '0' 转成字符(否则存的是 ASCII 码)
        n/=k;                   // 整除 k,去掉已经取走的最低位
    }
    reverse(s.begin(),s.end());// 短除法先得到低位,必须反转才是正常书写顺序
    cout<<s<<"\n";              // 输出结果并换行
    return 0;
}
